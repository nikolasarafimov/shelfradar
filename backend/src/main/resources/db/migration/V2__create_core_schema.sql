CREATE EXTENSION IF NOT EXISTS pgcrypto;


-- =========================================================
-- USERS
-- =========================================================

CREATE TABLE app_users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(150) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(30)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_app_users_role
        CHECK (role IN ('ADMIN', 'STORE_OWNER'))
);

CREATE UNIQUE INDEX uq_app_users_email_ci
    ON app_users (LOWER(email));


-- =========================================================
-- BRANDS
-- =========================================================

CREATE TABLE brands
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL
);

CREATE UNIQUE INDEX uq_brands_name_ci
    ON brands (LOWER(name));


-- =========================================================
-- CATEGORIES
-- =========================================================

CREATE TABLE categories
(
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL
);

CREATE UNIQUE INDEX uq_categories_name_ci
    ON categories (LOWER(name));


-- =========================================================
-- PRODUCTS
-- =========================================================

CREATE TABLE products
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(200) NOT NULL,
    description TEXT,
    image_url   VARCHAR(1000),

    brand_id    BIGINT NOT NULL,
    category_id BIGINT NOT NULL,

    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_products_brand
        FOREIGN KEY (brand_id)
            REFERENCES brands (id),

    CONSTRAINT fk_products_category
        FOREIGN KEY (category_id)
            REFERENCES categories (id)
);

CREATE INDEX idx_products_name_lower
    ON products (LOWER(name));

CREATE INDEX idx_products_brand_id
    ON products (brand_id);

CREATE INDEX idx_products_category_id
    ON products (category_id);


-- =========================================================
-- STORES
-- =========================================================

CREATE TABLE stores
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name          VARCHAR(200) NOT NULL,
    address       VARCHAR(300) NOT NULL,
    city          VARCHAR(120) NOT NULL,

    latitude      NUMERIC(9, 6) NOT NULL,
    longitude     NUMERIC(9, 6) NOT NULL,

    location      GEOGRAPHY(POINT, 4326)
        GENERATED ALWAYS AS (
            ST_SetSRID(
                ST_MakePoint(
                    longitude::DOUBLE PRECISION,
                    latitude::DOUBLE PRECISION
                ),
                4326
            )::GEOGRAPHY
        ) STORED,

    phone         VARCHAR(50),
    working_hours VARCHAR(255),

    status        VARCHAR(30) NOT NULL DEFAULT 'PENDING',

    owner_id      BIGINT NOT NULL,

    created_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_stores_latitude
        CHECK (latitude BETWEEN -90 AND 90),

    CONSTRAINT chk_stores_longitude
        CHECK (longitude BETWEEN -180 AND 180),

    CONSTRAINT chk_stores_status
        CHECK (status IN ('PENDING', 'ACTIVE', 'INACTIVE')),

    CONSTRAINT fk_stores_owner
        FOREIGN KEY (owner_id)
            REFERENCES app_users (id)
);

CREATE INDEX idx_stores_owner_id
    ON stores (owner_id);

CREATE INDEX idx_stores_city
    ON stores (city);

CREATE INDEX idx_stores_status
    ON stores (status);

CREATE INDEX idx_stores_location
    ON stores
    USING GIST (location);


-- =========================================================
-- INVENTORY
-- =========================================================

CREATE TABLE inventory
(
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    store_id   BIGINT NOT NULL,
    product_id BIGINT NOT NULL,

    price      NUMERIC(10, 2) NOT NULL,
    quantity   INTEGER NOT NULL,

    status     VARCHAR(30) NOT NULL,

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_inventory_price
        CHECK (price >= 0),

    CONSTRAINT chk_inventory_quantity
        CHECK (quantity >= 0),

    CONSTRAINT chk_inventory_status
        CHECK (
            status IN (
                       'IN_STOCK',
                       'LOW_STOCK',
                       'OUT_OF_STOCK'
                )
            ),

    CONSTRAINT fk_inventory_store
        FOREIGN KEY (store_id)
            REFERENCES stores (id)
            ON DELETE CASCADE,

    CONSTRAINT fk_inventory_product
        FOREIGN KEY (product_id)
            REFERENCES products (id)
            ON DELETE CASCADE,

    CONSTRAINT uq_inventory_store_product
        UNIQUE (store_id, product_id)
);

CREATE INDEX idx_inventory_product_id
    ON inventory (product_id);

CREATE INDEX idx_inventory_store_id
    ON inventory (store_id);

CREATE INDEX idx_inventory_status
    ON inventory (status);